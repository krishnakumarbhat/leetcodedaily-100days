'            result=[[1,0],[0,1]]',
'            while p:',
'                if p%2: result=mat_mul(result,M)',
'                M=mat_mul(M,M); p//=2',
'            return result',
'        M=[[1,1],[1,0]]',
'        return mat_pow(M,n)[0][0]',
