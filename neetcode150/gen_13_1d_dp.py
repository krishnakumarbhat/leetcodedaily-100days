'        r=Cls().longestPalindrome(s)',
'        t1=time.perf_counter(); mem=tracemalloc.get_traced_memory()[1]; tracemalloc.stop()',
'        print(f"var{Vi}: {r!r}, mem={mem}bytes, time={(t1-t0)*1e6:.2f}us")',
