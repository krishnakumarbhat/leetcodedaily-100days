class Solution:
    # Problem: Valid Anagram
    def isAnagram(self, s: str, t: str) -> bool:
        if len(s) != len(t):
            return False  # Early exit if lengths differ
        hashmap = {}
        
        for char in s:
            hashmap[char] = hashmap.get(char, 0) + 1
        
        for char in t:
            if char not in hashmap or hashmap[char] == 0:
                return False
            hashmap[char] -= 1
        
        return True

