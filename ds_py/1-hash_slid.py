class Solution:
    # i used bitmasking 
    def isValidSudoku(self, board: List[List[str]]) -> bool:
        rows = [0] * 9
        cols = [0] * 9
        squares = [0] * 9

        for r in range(9):
            for c in range(9):
                if board[r][c] == ".":
                    continue
                
                val = int(board[r][c]) - 1
                if (1 << val) & rows[r]:
                    return False
                if (1 << val) & cols[c]:
                    return False
                if (1 << val) & squares[(r // 3) * 3 + (c // 3)]:
                    return False
                    
                rows[r] |= (1 << val)
                cols[c] |= (1 << val)
                squares[(r // 3) * 3 + (c // 3)] |= (1 << val)
        return True
    
class Solution:
    # Function to find the length of the longest consecutive sequence
    def longestConsecutive(self, nums: List[int]) -> int:
        num_set = set(nums)
        longest_streak = 0
        
        for num in num_set:
            if num - 1 not in num_set:  # Start a new streak
                current_num = num
                current_streak = 1
                
                while current_num + 1 in num_set:  # Count consecutive numbers
                    current_num += 1
                    current_streak += 1
                
                longest_streak = max(longest_streak, current_streak)  # Update longest streak
        return longest_streak

